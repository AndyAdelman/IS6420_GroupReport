  , count(*) AS customized_order_lines
  , sum(i.quantity) AS affected_units
  , sum(oc.price_adjustment_charged * i.quantity) AS customization_sales
FROM dominos.order_item_customization oc
JOIN dominos.customization_option c
    ON c.option_id = oc.option_id
JOIN dominos.product p
    ON p.product_id = c.product_id
JOIN dominos.order_item i
    ON i.order_item_id = oc.order_item_id
JOIN dominos.v_completed_order o
    ON o.order_id = i.order_id
GROUP BY
    p.product_id
  , p.product_name
  , c.option_id
  , c.option_name
  , c.option_type
ORDER BY
    affected_units DESC
  , p.product_id
  , c.option_id;

-- Q06: Proposed subscription benefit usage
SELECT
    p.name AS plan_name
  , c.customer_id
  , c.first_name
  , cs.status
  , p.price AS listed_monthly_price
  , count(o.order_id) AS credits_used
  , coalesce(
        sum(
            CASE WHEN o.order_id IS NOT NULL
                 THEN b.value_applied
                 ELSE 0
            END
        )
      , 0
    ) AS credits_applied
  , p.benefit_limit_per_cycle AS monthly_credit_limit
FROM dominos.subscription_plan p
JOIN dominos.customer_subscription cs
    ON cs.plan_id = p.plan_id
JOIN dominos.customer c
    ON c.customer_id = cs.customer_id
LEFT JOIN dominos.subscription_benefit_event b
    ON b.customer_subscription_id = cs.customer_subscription_id
   AND b.event_datetime >= TIMESTAMPTZ '2026-09-01 00:00:00-06'
   AND b.event_datetime < TIMESTAMPTZ '2026-10-01 00:00:00-06'
LEFT JOIN dominos.v_completed_order o
    ON o.order_id = b.order_id
GROUP BY
    p.plan_id
  , p.name
  , c.customer_id
  , c.first_name
  , cs.customer_subscription_id
  , cs.status
  , p.price
  , p.benefit_limit_per_cycle
ORDER BY
    p.plan_id
  , c.customer_id;

-- Q07: Loyalty balances
SELECT
    c.customer_id
  , c.first_name
  , c.last_name
  , a.status
  , coalesce(sum(t.points), 0) AS points_balance
  , count(t.loyalty_transaction_id) FILTER (WHERE t.transaction_type = 'EARN') AS earning_events
FROM dominos.customer c
JOIN dominos.loyalty_account a
    ON a.customer_id = c.customer_id
LEFT JOIN dominos.loyalty_transaction t
    ON t.loyalty_account_id = a.loyalty_account_id
GROUP BY
    c.customer_id
  , c.first_name
  , c.last_name
  , a.loyalty_account_id
  , a.status
ORDER BY
    points_balance DESC
  , c.customer_id;

-- Q08: Fulfillment time by store
SELECT
    s.store_name
  , o.fulfillment_type
  , count(*) AS completed_unscheduled_orders
  , round(
  	(avg(date_part('epoch', e.status_datetime - o.order_datetime)) / 60)::NUMERIC
  , 2
) AS avg_minutes
  , round(
    (max(date_part('epoch', e.status_datetime - o.order_datetime)) / 60)::NUMERIC
  , 2
) AS max_minutes
FROM dominos.store s
JOIN dominos.orders o
    ON o.store_id = s.store_id
JOIN dominos.order_status_event e
    ON e.order_id = o.order_id
   AND e.status = 'COMPLETED'
JOIN dominos.v_order_current_status st
    ON st.order_id = o.order_id
   AND st.status = 'COMPLETED'
WHERE o.scheduled_datetime IS NULL
GROUP BY
    s.store_id
  , s.store_name
  , o.fulfillment_type
ORDER BY
    avg_minutes DESC
  , s.store_id
  , o.fulfillment_type;

-- Q09: Store menu and availability
SELECT
    s.store_name
  , c.category_name
  , p.product_name
  , v.size
  , v.crust_type
  , v.base_price
  , f.store_price
  , f.is_available
FROM dominos.store s
JOIN dominos.store_menu_offering f
    ON f.store_id = s.store_id
JOIN dominos.product_variation v
    ON v.variation_id = f.variation_id
JOIN dominos.product p
    ON p.product_id = v.product_id
JOIN dominos.menu_category c
    ON c.category_id = p.category_id
WHERE s.is_active
  AND p.is_active
  AND v.is_active
ORDER BY
    s.store_id
  , c.display_order
  , p.product_id
  , v.variation_id;

-- Q10: Open orders needing attention
WITH paid AS (
    SELECT
        order_id
      , sum(amount) AS collected
    FROM dominos.payment
    WHERE payment_status = 'SUCCEEDED'
    GROUP BY
        order_id
)
SELECT
    o.order_id
  , s.store_name
  , coalesce(btrim(c.first_name) || ' ' || btrim(c.last_name), o.guest_name) AS customer_name
  , st.status
  , o.total_amount
  , coalesce(p.collected, 0) AS collected
  , o.total_amount - coalesce(p.collected, 0) AS outstanding_amount
FROM dominos.orders o
JOIN dominos.store s
    ON s.store_id = o.store_id
LEFT JOIN dominos.customer c
    ON c.customer_id = o.customer_id
JOIN dominos.v_order_current_status st
    ON st.order_id = o.order_id
LEFT JOIN paid p
    ON p.order_id = o.order_id
WHERE st.status NOT IN ('COMPLETED', 'CANCELED')
ORDER BY
    o.order_datetime
  , o.order_id;
