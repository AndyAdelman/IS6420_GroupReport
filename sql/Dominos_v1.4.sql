-- Q01: Store sales and collections
WITH paid AS (
    SELECT
        order_id
      , sum(amount) AS collected
    FROM dominos.payment
    WHERE payment_status = 'SUCCEEDED'
    GROUP BY
        order_id
)
SELECT
    s.store_name
  , count(o.order_id) AS completed_orders
  , coalesce(sum(o.subtotal_amount - o.discount_amount), 0) AS net_food_sales
  , coalesce(sum(o.delivery_fee), 0) AS delivery_fees
  , coalesce(sum(o.tax_amount), 0) AS tax_collected
  , coalesce(sum(p.collected), 0) AS successful_collections
FROM dominos.store s
LEFT JOIN dominos.v_completed_order o
    ON o.store_id = s.store_id
   AND o.order_datetime >= TIMESTAMPTZ '2026-09-01 00:00:00-06'
   AND o.order_datetime < TIMESTAMPTZ '2026-10-01 00:00:00-06'
LEFT JOIN paid p
    ON p.order_id = o.order_id
GROUP BY
    s.store_id
  , s.store_name
ORDER BY
    net_food_sales DESC
  , s.store_id;

-- Q02: Bestselling products
SELECT
    p.product_name
  , c.category_name
  , sum(i.quantity) AS units_sold
  , sum(a.line_amount) AS gross_item_sales
FROM dominos.order_item i
JOIN dominos.v_order_item_amount a
    ON a.order_item_id = i.order_item_id
JOIN dominos.store_menu_offering f
    ON f.offering_id = i.offering_id
JOIN dominos.product_variation v
    ON v.variation_id = f.variation_id
JOIN dominos.product p
    ON p.product_id = v.product_id
JOIN dominos.menu_category c
    ON c.category_id = p.category_id
JOIN dominos.v_completed_order o
    ON o.order_id = i.order_id
GROUP BY
    p.product_id
  , p.product_name
  , c.category_name
ORDER BY
    units_sold DESC
  , p.product_id;

-- Q03: Customer purchasing activity
SELECT
    c.customer_id
  , btrim(c.first_name) || ' ' || btrim(c.last_name) AS customer_name
  , count(o.order_id) AS completed_orders
  , coalesce(sum(o.subtotal_amount - o.discount_amount), 0) AS net_food_spend
  , string_agg(DISTINCT s.store_name, ', ' ORDER BY s.store_name) AS stores_used
FROM dominos.customer c
LEFT JOIN dominos.v_completed_order o
    ON o.customer_id = c.customer_id
LEFT JOIN dominos.store s
    ON s.store_id = o.store_id
GROUP BY
    c.customer_id
  , c.first_name
  , c.last_name
ORDER BY
    net_food_spend DESC
  , c.customer_id;

-- Q04: Promotion usage
SELECT
    p.promo_code
  , p.is_active
  , count(o.order_id) AS completed_redemptions
  , coalesce(
        sum(
            CASE WHEN o.order_id IS NOT NULL
                 THEN op.discount_amount_applied
                 ELSE 0
            END
        )
      , 0
    ) AS discounts_given
  , round(avg(o.subtotal_amount - o.discount_amount), 2) AS avg_net_food_sale
FROM dominos.promotion p
LEFT JOIN dominos.order_promotion op
    ON op.promotion_id = p.promotion_id
LEFT JOIN dominos.v_completed_order o
    ON o.order_id = op.order_id
GROUP BY
    p.promotion_id
  , p.promo_code
  , p.is_active
ORDER BY
    completed_redemptions DESC
  , p.promotion_id;

