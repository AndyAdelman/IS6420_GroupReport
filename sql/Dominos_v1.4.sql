DROP SCHEMA IF EXISTS dominos CASCADE;
CREATE SCHEMA dominos;
SET search_path TO dominos, public;
SET TIME ZONE 'America/Denver';

CREATE TABLE customer (
 customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name varchar(50) NOT NULL CHECK (btrim(first_name) <> ''),
 last_name varchar(50) NOT NULL CHECK (btrim(last_name) <> ''),
 email varchar(100) NOT NULL CHECK (email LIKE '%_@_%._%'),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX customer_email_unique ON customer (lower(btrim(email)));

CREATE TABLE store (
 store_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_number varchar(20) NOT NULL UNIQUE,
 store_name varchar(100) NOT NULL,
 street varchar(100) NOT NULL,
 city varchar(50) NOT NULL,
 state char(2) NOT NULL CHECK (state ~ '^[A-Z]{2}$'),
 zip_code varchar(10) NOT NULL CHECK (zip_code ~ '^[0-9]{5}(-[0-9]{4})?$'),
 phone varchar(20),
 is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE address (
 address_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer REFERENCES customer(customer_id),
 street varchar(100) NOT NULL,
 city varchar(50) NOT NULL,
 state char(2) NOT NULL CHECK (state ~ '^[A-Z]{2}$'),
 zip_code varchar(10) NOT NULL CHECK (zip_code ~ '^[0-9]{5}(-[0-9]{4})?$'),
 is_default boolean NOT NULL DEFAULT false,
 CHECK (NOT is_default OR customer_id IS NOT NULL)
);

CREATE UNIQUE INDEX one_default_address_per_customer ON address(customer_id) WHERE is_default;

CREATE TABLE menu_category (
 category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_name varchar(50) NOT NULL UNIQUE,
 display_order integer NOT NULL CHECK (display_order > 0)
);

CREATE TABLE product (
 product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id integer NOT NULL REFERENCES menu_category(category_id),
 product_name varchar(100) NOT NULL,
 description varchar(225),
 is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE product_variation (
 variation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id integer NOT NULL REFERENCES product(product_id),
 crust_type varchar(30) NOT NULL CHECK (crust_type IN ('HAND_TOSSED','THIN','NOT_APPLICABLE')),
 size varchar(30) NOT NULL CHECK (size IN ('MEDIUM','LARGE','REGULAR','BOTTLE_20OZ','BOTTLE_2L')),
 base_price numeric(8,2) NOT NULL CHECK (base_price >= 0),
 is_active boolean NOT NULL DEFAULT true,
 UNIQUE(product_id, crust_type, size)
);

CREATE TABLE store_menu_offering (
 offering_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id integer NOT NULL REFERENCES store(store_id),
 variation_id integer NOT NULL REFERENCES product_variation(variation_id),
 store_price numeric(8,2) NOT NULL CHECK (store_price >= 0),
 is_available boolean NOT NULL DEFAULT true,
 UNIQUE(store_id, variation_id)
);

CREATE TABLE customization_option (
 option_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id integer NOT NULL REFERENCES product(product_id),
 option_name varchar(50) NOT NULL,
 option_type varchar(30) NOT NULL CHECK (option_type IN ('ADD','REMOVE')),
 price numeric(8,2) NOT NULL CHECK (price >= 0),
 is_active boolean NOT NULL DEFAULT true,
 UNIQUE(product_id, option_name, option_type)
);

CREATE TABLE promotion (
 promotion_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 promo_code varchar(30) NOT NULL UNIQUE,
 description varchar(225),
 discount_type varchar(20) NOT NULL CHECK (discount_type IN ('FIXED','PERCENT')),
 discount_value numeric(8,2) NOT NULL CHECK (discount_value > 0),
 starts_date date NOT NULL,
 ends_date date,
 is_active boolean NOT NULL DEFAULT true,
 CHECK (ends_date IS NULL OR ends_date >= starts_date),
 CHECK (discount_type <> 'PERCENT' OR discount_value <= 100)
);

-- Proposed venture: monthly meal-credit membership. Team must validate novelty.
CREATE TABLE subscription_plan (
 plan_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(50) NOT NULL UNIQUE,
 price numeric(8,2) NOT NULL CHECK (price > 0),
 billing_cycle varchar(20) NOT NULL DEFAULT 'MONTHLY' CHECK (billing_cycle = 'MONTHLY'),
 benefit_description varchar(225) NOT NULL,
 benefit_amount numeric(8,2) NOT NULL CHECK (benefit_amount > 0),
 benefit_limit_per_cycle integer NOT NULL CHECK (benefit_limit_per_cycle > 0),
 is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE customer_subscription (
 customer_subscription_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer NOT NULL REFERENCES customer(customer_id),
 plan_id integer NOT NULL REFERENCES subscription_plan(plan_id),
 status varchar(20) NOT NULL CHECK (status IN ('ACTIVE','CANCELED','EXPIRED')),
 start_date date NOT NULL,
 renewal_date date,
 cancel_date date,
 CHECK (renewal_date IS NULL OR renewal_date > start_date),
 CHECK (cancel_date IS NULL OR cancel_date >= start_date),
 CHECK ((status = 'CANCELED') = (cancel_date IS NOT NULL))
);

CREATE UNIQUE INDEX one_active_subscription_per_customer ON customer_subscription(customer_id) WHERE status = 'ACTIVE';

CREATE TABLE orders (
 order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer REFERENCES customer(customer_id),
 store_id integer NOT NULL REFERENCES store(store_id),
 delivery_address_id integer REFERENCES address(address_id),
 fulfillment_type varchar(10) NOT NULL CHECK (fulfillment_type IN ('DELIVERY','CARRYOUT')),
 guest_name varchar(100),
 guest_email varchar(100),
 guest_phone varchar(20),
 subtotal_amount numeric(10,2) NOT NULL CHECK (subtotal_amount >= 0),
 tax_amount numeric(10,2) NOT NULL CHECK (tax_amount >= 0),
 discount_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
 delivery_fee numeric(8,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
 total_amount numeric(10,2) NOT NULL CHECK (total_amount >= 0),
 order_datetime timestamptz NOT NULL,
 scheduled_datetime timestamptz,
 CHECK (discount_amount <= subtotal_amount),
 CHECK (total_amount = subtotal_amount - discount_amount + tax_amount + delivery_fee),
 CHECK ((fulfillment_type = 'DELIVERY' AND delivery_address_id IS NOT NULL)
     OR (fulfillment_type = 'CARRYOUT' AND delivery_address_id IS NULL AND delivery_fee = 0)),
 CHECK (customer_id IS NOT NULL OR
     (guest_name IS NOT NULL AND btrim(guest_name) <> '' AND guest_phone IS NOT NULL AND btrim(guest_phone) <> '')),
 CHECK (scheduled_datetime IS NULL OR scheduled_datetime >= order_datetime)
);

CREATE TABLE order_item (
 order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id integer NOT NULL REFERENCES orders(order_id),
 offering_id integer NOT NULL REFERENCES store_menu_offering(offering_id),
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_price numeric(8,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE order_item_customization (
 order_item_id integer NOT NULL REFERENCES order_item(order_item_id),
 option_id integer NOT NULL REFERENCES customization_option(option_id),
 price_adjustment_charged numeric(8,2) NOT NULL CHECK (price_adjustment_charged >= 0),
 PRIMARY KEY(order_item_id, option_id)
);

CREATE TABLE order_promotion (
 order_id integer NOT NULL REFERENCES orders(order_id),
 promotion_id integer NOT NULL REFERENCES promotion(promotion_id),
 discount_amount_applied numeric(8,2) NOT NULL CHECK (discount_amount_applied > 0),
 PRIMARY KEY(order_id, promotion_id),
 -- Working-draft rule: at most one promotion on an order.
 UNIQUE(order_id)
);

CREATE TABLE payment (
 payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id integer NOT NULL REFERENCES orders(order_id),
 payment_method varchar(30) NOT NULL CHECK (payment_method IN ('CARD','CASH','DIGITAL_WALLET')),
 payment_status varchar(20) NOT NULL CHECK (payment_status IN ('PENDING','SUCCEEDED','FAILED')),
 amount numeric(10,2) NOT NULL CHECK (amount > 0),
 payment_datetime timestamptz NOT NULL
);

CREATE TABLE order_status_event (
 status_event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id integer NOT NULL REFERENCES orders(order_id),
 status varchar(20) NOT NULL CHECK (status IN ('PLACED','PREPARING','BAKING','READY','OUT_FOR_DELIVERY','COMPLETED','CANCELED')),
 status_datetime timestamptz NOT NULL,
 UNIQUE(order_id, status_datetime)
);

CREATE TABLE loyalty_account (
 loyalty_account_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer NOT NULL UNIQUE REFERENCES customer(customer_id),
 status varchar(20) NOT NULL CHECK (status IN ('ACTIVE','SUSPENDED','CLOSED')),
 enrollment_date date NOT NULL
);

CREATE TABLE loyalty_transaction (
 loyalty_transaction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 loyalty_account_id integer NOT NULL REFERENCES loyalty_account(loyalty_account_id),
 order_id integer REFERENCES orders(order_id),
 transaction_type varchar(20) NOT NULL CHECK (transaction_type IN ('EARN','REDEEM','ADJUST')),
 points integer NOT NULL CHECK (points <> 0),
 transaction_datetime timestamptz NOT NULL,
 CHECK ((transaction_type = 'EARN' AND points > 0) OR
        (transaction_type = 'REDEEM' AND points < 0) OR transaction_type = 'ADJUST')
);

CREATE UNIQUE INDEX one_earn_per_account_order ON loyalty_transaction(loyalty_account_id,order_id) WHERE transaction_type = 'EARN';

CREATE TABLE subscription_benefit_event (
 benefit_event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_subscription_id integer NOT NULL REFERENCES customer_subscription(customer_subscription_id),
 order_id integer NOT NULL UNIQUE REFERENCES orders(order_id),
 event_datetime timestamptz NOT NULL,
 benefit_description varchar(225) NOT NULL,
 value_applied numeric(8,2) NOT NULL CHECK (value_applied > 0)
);

CREATE INDEX orders_customer_date_idx ON orders(customer_id,order_datetime);
CREATE INDEX orders_store_date_idx ON orders(store_id,order_datetime);
CREATE INDEX order_item_order_idx ON order_item(order_id);
CREATE INDEX payment_order_idx ON payment(order_id);
CREATE INDEX status_order_time_idx ON order_status_event(order_id,status_datetime DESC);
CREATE INDEX benefit_subscription_idx ON subscription_benefit_event(customer_subscription_id);
CREATE INDEX loyalty_account_time_idx ON loyalty_transaction(loyalty_account_id,transaction_datetime);

-- Views reduce repeated logic and avoid counting an order once per joined item/payment.
CREATE VIEW v_order_current_status AS
 SELECT DISTINCT ON (order_id) order_id,status,status_datetime
 FROM order_status_event ORDER BY order_id,status_datetime DESC,status_event_id DESC;

CREATE VIEW v_order_item_amount AS
 SELECT i.order_item_id,i.order_id,i.offering_id,i.quantity,i.unit_price,
        coalesce(c.adjustment,0)::numeric(8,2) AS customization_per_unit,
        (i.quantity*(i.unit_price+coalesce(c.adjustment,0)))::numeric(10,2) AS line_amount
 FROM order_item i
 LEFT JOIN (SELECT order_item_id,sum(price_adjustment_charged) AS adjustment
            FROM order_item_customization GROUP BY order_item_id) c USING(order_item_id);

CREATE VIEW v_completed_order AS
 SELECT o.* FROM orders o JOIN v_order_current_status s USING(order_id)
 WHERE s.status = 'COMPLETED';

